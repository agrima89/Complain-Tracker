# ---------------- NUMBERED CANVAS FOR DYNAMIC 2-PASS FOOTERS ----------------

class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that computes total pages dynamically and renders
    standardized institutional headers, footers, rules, and page numbers.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages):
        self.saveState()
        width, height = self._pagesize

        # Running Footer Decorative Line
        self.setStrokeColor(BORDER_COLOR)
        self.setLineWidth(0.75)
        self.line(40, 42, width - 40, 42)

        # Footer Left: System Attribution & Timestamp
        self.setFont("Helvetica", 8)
        self.setFillColor(TEXT_MUTED)
        self.drawString(
            40,
            28,
            "Generated by College Complaint & Solution Tracker  |  CampusCare Grievance Redressal System"
        )

        # Footer Right: Page Count
        page_str = f"Page {self._pageNumber} of {total_pages}"
        self.drawRightString(width - 40, 28, page_str)

        # Small security note
        self.setFont("Helvetica-Oblique", 7)
        self.setFillColor(TEXT_LIGHT)
        self.drawRightString(
            width - 40,
            16,
            "Official Institutional Record • Valid without physical signature"
        )

        self.restoreState()


# ---------------- FILENAME FORMATTER ----------------

def sanitize_filename_part(text):
    """Converts a string into a clean, safe filename token."""
    if not text:
        return "Student"
    cleaned = re.sub(r"[^\w\s-]", "", str(text)).strip()
    return re.sub(r"[-\s]+", "_", cleaned)


def get_pdf_filename(complaint_id, student_name):
    """
    Generates standardized filename: Complaint_<ComplaintID>_<StudentName>.pdf
    Example: Complaint_1023_Student_Name.pdf
    """
    safe_name = sanitize_filename_part(student_name)
    cid_str = str(complaint_id)
    return f"Complaint_{cid_str}_{safe_name}.pdf"


def get_summary_pdf_filename():
    """Generates standardized filename for summary report."""
    date_str = datetime.now().strftime("%Y-%m-%d")
    return f"Complaint_Summary_Report_{date_str}.pdf"


