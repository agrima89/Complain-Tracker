def format_location_string(complaint):
    """Combines block, floor, room, and corridor into a clean descriptive string."""
    parts = []
    block = complaint["block"] if "block" in complaint.keys() and complaint["block"] else ""
    floor_no = complaint["floor_no"] if "floor_no" in complaint.keys() and complaint["floor_no"] else ""
    room_no = complaint["room_no"] if "room_no" in complaint.keys() and complaint["room_no"] else ""
    corridor = complaint["corridor_side"] if "corridor_side" in complaint.keys() and complaint["corridor_side"] else ""
    nearby = complaint["nearby_area"] if "nearby_area" in complaint.keys() and complaint["nearby_area"] else ""

    if block:
        parts.append(f"Block: {block}")
    if floor_no:
        parts.append(f"{floor_no}")
    if room_no:
        parts.append(f"Room: {room_no}")
    if corridor:
        parts.append(f"Side: {corridor}")
    if nearby:
        parts.append(f"Near: {nearby}")

    if parts:
        return ", ".join(parts)
    return complaint["location"] if "location" in complaint.keys() and complaint["location"] else "Campus Premises"


